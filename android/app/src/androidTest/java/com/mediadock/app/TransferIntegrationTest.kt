package com.mediadock.app

import android.net.Uri
import androidx.compose.material3.Text
import androidx.compose.ui.test.junit4.createComposeRule
import androidx.room.Room
import androidx.test.platform.app.InstrumentationRegistry
import com.mediadock.app.core.database.MediaDockDatabase
import com.mediadock.app.core.database.entity.DownloadEntity
import com.mediadock.app.core.datastore.PreferencesDataStore
import com.mediadock.app.core.downloads.DownloadTransferEngine
import com.mediadock.app.core.network.MediaDockApi
import com.mediadock.app.core.storage.StorageManager
import kotlinx.coroutines.*
import kotlinx.coroutines.flow.first
import okhttp3.MediaType
import okhttp3.ResponseBody
import okio.Buffer
import okio.BufferedSource
import org.junit.*
import org.junit.Assert.*
import retrofit2.Response
import java.lang.reflect.Proxy
import java.util.UUID

class TransferIntegrationTest {
    @get:Rule val compose = createComposeRule()
    private val context get() = InstrumentationRegistry.getInstrumentation().targetContext
    private lateinit var database: MediaDockDatabase
    private var output: Uri? = null

    @Before fun before() {
        check(context.packageName.endsWith(".debug"))
        database = Room.inMemoryDatabaseBuilder(context, MediaDockDatabase::class.java).build()
        compose.setContent { Text("MediaDock transfer integration test") }
        compose.waitForIdle()
    }
    @After fun after() {
        // Only the output generated by this test is removed.
        output?.let { context.contentResolver.delete(it, null, null) }
        database.close()
    }

    private suspend fun transfer(truncated: Boolean): Pair<String, ByteArray> {
        val payload = ByteArray(65536) { (it % 251).toByte() }
        val body = object : ResponseBody() {
            override fun contentType(): MediaType? = null
            override fun contentLength() = payload.size.toLong() + if (truncated) 100 else 0
            override fun source(): BufferedSource = Buffer().write(payload)
        }
        val api = Proxy.newProxyInstance(MediaDockApi::class.java.classLoader, arrayOf(MediaDockApi::class.java)) { _, method, _ ->
            check(method.name == "streamFile") { "This fixture must never contact an external service" }
            Response.success(body)
        } as MediaDockApi
        val prefs = PreferencesDataStore(context)
        prefs.setWifiOnly(false)
        val engine = DownloadTransferEngine(context, api, database.downloadDao(), database.historyDao(), StorageManager(context), prefs)
        val id = UUID.randomUUID().toString()
        database.downloadDao().insertOrUpdate(DownloadEntity(id, "https://example.com/original", "MediaDock-test-$id", "other", "bin", "original"))
        engine.startFileTransfer(id, "https://example.com/temporary-signed-output", "MediaDock-test-$id", "other", "bin", payload.size.toLong())
        withTimeout(15000) { while (engine.isTransferring(id)) delay(50) }
        return id to payload
    }

    @Test fun savesEveryByteAndKeepsOriginalSourceInLibrary() = runBlocking {
        val (id, payload) = transfer(false)
        val job = requireNotNull(database.downloadDao().getDownloadSync(id))
        assertEquals("COMPLETED", job.status)
        assertEquals(payload.size.toLong(), job.downloadedBytes)
        output = Uri.parse(job.localUri)
        assertArrayEquals(payload, context.contentResolver.openInputStream(output!!)?.use { it.readBytes() })
        val history = database.historyDao().getAllHistory().first().single()
        assertEquals("https://example.com/original", history.sourceUrl)
        assertEquals(payload.size.toLong(), history.fileSizeBytes)
    }

    @Test fun truncatedTransferIsFailedAndNeverAddedToLibrary() = runBlocking {
        val (id, _) = transfer(true)
        val job = requireNotNull(database.downloadDao().getDownloadSync(id))
        assertEquals("FAILED", job.status)
        assertNull(job.localUri)
        assertTrue(database.historyDao().getAllHistory().first().isEmpty())
        assertTrue(database.downloadDao().getActiveDownloads().first().any { it.jobId == id })
    }
}
